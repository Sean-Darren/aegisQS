"""Regenerate the deterministic sample PDF, citation manifest, and HTTP payload.
Uses reportlab/pdfplumber from the Codex bundled Python runtime (not app dependencies).
"""
from pathlib import Path
import base64
import json
import pdfplumber
from reportlab.pdfgen import canvas

ROOT = Path(__file__).resolve().parents[1]
PDF = ROOT / 'public/mock-docs/sample-priced-boq.pdf'
PDF.parent.mkdir(parents=True, exist_ok=True)
width, height = 595, 842
c = canvas.Canvas(str(PDF), pagesize=(width, height), invariant=1)
c.setTitle('Central Market Rehab Phase 2 - fictional priced BOQ excerpts')
entries = []
for page in range(10):
    c.setFillColorRGB(.17,.13,.11)
    c.setFont('Helvetica-Bold', 16)
    c.drawString(40, 794, 'Central Market Rehab Phase 2')
    c.setFont('Helvetica', 10)
    c.drawString(40, 772, 'Fictional sample priced BOQ - evidence viewer test document')
    c.drawString(40, 751, 'Recorded unit rates require independent quantity surveyor review.')
    c.setLineWidth(.5)
    c.line(40, 738, 555, 738)
    for row in range(15):
        i = (page*15 + row)*20
        ref = f'BQ-{i+1:04d}'
        rate = round((100+(i%100)*12)*.7,2)
        excerpt = f'{ref} | Recorded unit rate: HK${rate:,.2f} / m2'
        baseline = 705 - row*40
        c.setFont('Helvetica', 11)
        c.drawString(40, baseline, excerpt)
        c.setFont('Helvetica', 9)
        c.drawString(40, baseline-14, 'Tender qualification: confirm the extent of repair before award.')
        entries.append({'boqItemRef':ref, 'page':page+1, 'excerpt':excerpt})
    c.setFont('Helvetica', 9)
    c.drawString(40, 55, 'Sample data only. This document is not a signed assessment report.')
    c.drawRightString(555, 55, f'{page+1} / 10')
    c.showPage()
c.save()
with pdfplumber.open(PDF) as pdf:
    for entry in entries:
        page = pdf.pages[entry['page']-1]
        match = page.search(entry['excerpt'], regex=False)[0]
        x, y = match['x0']-2, match['top']-2
        entry['bbox'] = {'x':x/width,'y':y/height,'w':(match['x1']-x+2)/width,'h':(match['bottom']-y+2)/height}
        box = entry['bbox']
        crop = page.crop((box['x']*width,box['y']*height,(box['x']+box['w'])*width,(box['y']+box['h'])*height))
        assert entry['excerpt'] == crop.extract_text()
manifest = ROOT/'src/mocks/fixtures/pdf-evidence.json'
manifest.write_text(json.dumps(entries,indent=2)+'\n')
payload = base64.b64encode(PDF.read_bytes()).decode()
(ROOT/'src/mocks/fixtures/pdf.ts').write_text('// Generated by scripts/generate-mock-pdf.py; identical to public/mock-docs/sample-priced-boq.pdf.\nexport const samplePdfBase64 = '+json.dumps(payload)+';\n')
print(f'Created {PDF}: {len(entries)} verified bounding boxes across 10 pages')
