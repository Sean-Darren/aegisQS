import { expect, test } from "vitest";
import * as s from "@/schemas";
import * as f from "@/mocks/fixtures/data";
import { users } from "@/mocks/fixtures/users";
import { diffWorkbooks } from "@/mocks/workbook-engine";
test("every entity fixture parses through its §7 schema", () => {
  for (const user of users) s.userSchema.parse(user);
  s.projectSchema.parse(f.project);
  const collections: [
    satisfiesSchema: { parse: (input: unknown) => unknown },
    fixtures: unknown[],
  ][] = [
    [s.hubDocumentSchema, f.documents],
    [s.documentVersionSchema, f.versions],
    [s.versionConflictSchema, f.conflicts],
    [s.entityLinkSchema, f.links],
    [s.drawingComparisonSchema, f.comparisons],
    [s.drawingChangeSchema, f.changes],
    [s.variationEventSchema, f.variations],
    [s.workbookSchema, f.workbooks],
    [s.workbookVersionSchema, f.workbookVersions],
    [s.workbookCheckSchema, f.checks],
    [s.boqItemSchema, f.boqItems],
    [s.materialSchema, f.materials],
    [s.priceForecastSchema, f.forecasts],
    [s.procurementAdviceSchema, f.procurement],
    [s.projectMaterialNeedSchema, f.materialNeeds],
    [s.auditEventSchema, f.auditEvents],
  ];
  for (const [schema, fixtures] of collections) {
    expect(fixtures.length).toBeGreaterThan(0);
    for (const fixture of fixtures) schema.parse(fixture);
  }
  for (const line of f.variations[0].costLines) s.costLineSchema.parse(line);
  s.columnMappingSchema.parse(f.workbooks[0].mapping);
  const diff = diffWorkbooks(
    "WV-1",
    "WV-2",
    f.boqItems.filter((i) => i.workbookVersionId === "WV-1"),
    f.boqItems.filter((i) => i.workbookVersionId === "WV-2"),
  );
  s.workbookDiffSchema.parse(diff);
  expect(diff.summary.added).toBe(3);
  for (const event of [
    {
      type: "comparison.progress",
      comparisonId: "CMP-A201",
      status: "detecting",
      progressPct: 50,
    },
    {
      type: "comparison.completed",
      comparisonId: "CMP-A201",
      status: "succeeded",
      changeCount: 4,
    },
    {
      type: "document.version_added",
      documentId: "D-A201",
      versionId: "D-A201-v3",
      conflict: false,
    },
    {
      type: "workbook.checked",
      workbookId: "WB-001",
      versionId: "WV-2",
      checkSummary: f.workbookVersions[1].checkSummary,
    },
  ])
    s.wsEventSchema.parse(event);
});
test("connected fixtures match the required demo numbers", () => {
  expect(f.documents).toHaveLength(40);
  expect(new Set(f.documents.map((d) => d.category)).size).toBe(5);
  expect(f.variations).toHaveLength(6);
  expect(
    f.variations[0].costLines.reduce((sum, line) => sum + line.amount, 0),
  ).toBe(186400);
  expect(f.variations[0].indicativeCost).toMatchObject({
    total: 186400,
    low: 171000,
    high: 203000,
  });
  expect(
    f.materialNeeds.find(
      (n) => n.materialId === "rebar" && n.source === "variation",
    )?.quantity,
  ).toBe(4.2);
  expect(f.materials).toHaveLength(10);
  for (const forecast of f.forecasts) {
    expect(forecast.history).toHaveLength(60);
    expect(forecast.forecast).toHaveLength(12);
  }
  expect(
    f.forecasts[0].forecast[5].p50 / f.materials[0].latestPrice - 1,
  ).toBeCloseTo(0.06, 4);
  expect(f.changes.filter((c) => c.comparisonId === "CMP-A201")).toHaveLength(
    4,
  );
  expect(f.changes.filter((c) => c.comparisonId === "CMP-S110")).toHaveLength(
    2,
  );
  for (const doc of f.documents) {
    expect(
      f.versions.filter(
        (v) => v.documentId === doc.id && v.status === "current",
      ),
    ).toHaveLength(1);
  }
});
test("invalid geometry, forecast bands and derived amounts are rejected", () => {
  expect(() => s.bboxSchema.parse({ x: 0.9, y: 0, w: 0.2, h: 0.1 })).toThrow();
  expect(() =>
    s.costLineSchema.parse({ ...f.variations[0].costLines[0], amount: 1 }),
  ).toThrow();
  const forecast = structuredClone(f.forecasts[0]);
  forecast.forecast[0].p10 = forecast.forecast[0].p90 + 1;
  expect(() => s.priceForecastSchema.parse(forecast)).toThrow();
});

test("file metadata and download fixtures match the actual generated bytes", async () => {
  const { readFileSync } = await import("node:fs");
  const { createHash } = await import("node:crypto");
  for (const version of f.versions) {
    const bytes = readFileSync(`public/mock-files/${f.filePaths[version.id]}`);
    expect(bytes.length).toBe(version.sizeBytes);
    expect(createHash("sha256").update(bytes).digest("hex")).toBe(
      version.sha256,
    );
  }
});
